#!/usr/bin/env bash
# Print the Homebrew formula for a release, from its checksums file.
#
#   scripts/brew-formula.sh <version> <checksums.txt> > Formula/ringmaster.rb
#
# The formula installs the release archive into libexec and links
# bin/ringmaster, so the launcher still finds share/ringmaster/web beside it.
set -euo pipefail

version="${1:?usage: scripts/brew-formula.sh <version> <checksums.txt>}"
sums="${2:?usage: scripts/brew-formula.sh <version> <checksums.txt>}"
repo="rigels-dev/ringmaster"
base="https://github.com/$repo/releases/download/$version"

sha() {
  local name="ringmaster-$version-$1.tar.gz"
  local value
  value="$(grep " $name\$" "$sums" | cut -d' ' -f1)"
  if [ -z "$value" ]; then
    echo "no checksum for $name in $sums" >&2
    exit 1
  fi
  printf '%s' "$value"
}

# Look every checksum up first: a missing one must stop the script, which an
# expansion inside the heredoc below would not do
darwin_arm64="$(sha darwin-arm64)"
darwin_amd64="$(sha darwin-amd64)"
linux_arm64="$(sha linux-arm64)"
linux_amd64="$(sha linux-amd64)"

cat <<RUBY
# Generated by scripts/brew-formula.sh for $version; do not edit by hand.
class Ringmaster < Formula
  desc "Local orchestration control plane for LLM coding agents"
  homepage "https://github.com/$repo"
  version "${version#v}"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/ringmaster-$version-darwin-arm64.tar.gz"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$base/ringmaster-$version-darwin-amd64.tar.gz"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$base/ringmaster-$version-linux-arm64.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$base/ringmaster-$version-linux-amd64.tar.gz"
      sha256 "$linux_amd64"
    end
  end

  # The web UI's server runs on Node.js; git drives the task worktrees
  depends_on "git"
  depends_on "node"

  def install
    libexec.install Dir["*"]
    bin.install_symlink libexec/"bin/ringmaster"
  end

  def caveats
    <<~EOS
      Configure providers and agents with:
        ringmaster config
      The fleet config lives in ~/.config/ringmaster/ringmaster.toml.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ringmaster --version")
  end
end
RUBY
